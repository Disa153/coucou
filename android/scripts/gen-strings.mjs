// Generates app/src/main/res/values/strings.xml from i18n/app-strings.json (English, the source) and
// values-ru/strings.xml from i18n/app-strings.ru.json (Russian: the same keys and placeholders).
// Usage: node android/scripts/gen-strings.mjs [--check]
// --check writes nothing and exits 1 if the committed file is stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LANGS = [
  { file: "i18n/app-strings.json", target: "app/src/main/res/values/strings.xml" },
  { file: "i18n/app-strings.ru.json", target: "app/src/main/res/values-ru/strings.xml" },
];
const english = JSON.parse(fs.readFileSync(path.join(root, LANGS[0].file), "utf8")).strings;

const BS = String.fromCharCode(92);
const esc = (s) =>
  s.split(BS).join(BS + BS)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/'/g, BS + "'").replace(/"/g, BS + '"')
    .replace(/^([@?])/, BS + "$1");

const holders = (v) => (v.match(/%\d\$[sd]|%%/g) || []).sort().join(" ");
let stale = false;
for (const lang of LANGS) {
  const app = JSON.parse(fs.readFileSync(path.join(root, lang.file), "utf8")).strings;
  // Placeholders must be positional printf arguments (%1$s), not {name}.
  if (Object.values(app).some((v) => /\{\w+\}/.test(v))) {
    console.error(`${lang.file}: placeholders are not supported; use %1$s.`);
    process.exit(2);
  }
  // A translation has exactly the English keys, with the same placeholders.
  for (const k of Object.keys(english)) {
    if (!(k in app)) { console.error(`${lang.file}: missing ${k}`); process.exit(2); }
    if (holders(app[k]) !== holders(english[k])) { console.error(`${lang.file}: ${k} has other placeholders`); process.exit(2); }
  }
  for (const k of Object.keys(app)) if (!(k in english)) { console.error(`${lang.file}: unknown ${k}`); process.exit(2); }
  // Same order as the English file.
  const xml =
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/scripts/gen-strings.mjs. Do not edit. -->\n<resources>\n` +
    Object.keys(english).map((k) => `    <string name="${k}">${esc(app[k])}</string>`).join("\n") + `\n</resources>\n`;
  const target = path.join(root, lang.target);
  if (process.argv.includes("--check")) {
    // Windows checkouts may turn LF into CRLF; the content is what matters.
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== xml) {
      console.error(`stale: ${path.relative(root, target)}`);
      stale = true;
    }
    continue;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, xml);
  console.log(`${lang.target}: ${Object.keys(app).length} strings`);
}
if (process.argv.includes("--check")) process.exit(stale ? 1 : 0);
